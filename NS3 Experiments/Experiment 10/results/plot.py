import csv
import os
import matplotlib.pyplot as plt
import numpy as np

# Ensure you have matplotlib installed: pip install matplotlib numpy

protocols = ['rip', 'ospf', 'aodv']
scenarios = ['normal', 'congestion', 'failure']

# Initialize data structures for our 3 metrics
metrics = {
    'pdr': {'data': {p: [] for p in protocols}, 'title': 'Packet Delivery Ratio (PDR)', 'ylabel': 'PDR (%)', 'file': 'chart_pdr.png'},
    'delay': {'data': {p: [] for p in protocols}, 'title': 'Average End-to-End Delay', 'ylabel': 'Delay (ms)', 'file': 'chart_delay.png'},
    'throughput': {'data': {p: [] for p in protocols}, 'title': 'Throughput', 'ylabel': 'Throughput (Mbps)', 'file': 'chart_throughput.png'}
}

# 1. Read the CSV files generated by NS-3
for p in protocols:
    for s in scenarios:
        filepath = f"results/summary_{p}_{s}.csv"
        try:
            with open(filepath, 'r') as f:
                reader = csv.DictReader(f)
                for row in reader:
                    metrics['pdr']['data'][p].append(float(row['pdr_percent']))
                    metrics['delay']['data'][p].append(float(row['avg_delay_ms']))
                    metrics['throughput']['data'][p].append(float(row['throughput_mbps']))
        except FileNotFoundError:
            print(f"Warning: {filepath} not found. Inserting 0.")
            for m in metrics:
                metrics[m]['data'][p].append(0.0)

# 2. Generate and save the plots
x = np.arange(len(scenarios))
width = 0.25
colors = ['#1f77b4', '#ff7f0e', '#2ca02c'] # Blue, Orange, Green

for key, metric in metrics.items():
    plt.figure(figsize=(9, 6))
    
    # Create grouped bars
    plt.bar(x - width, metric['data']['rip'], width, label='RIP', color=colors[0], edgecolor='black')
    plt.bar(x, metric['data']['ospf'], width, label='OSPF', color=colors[1], edgecolor='black')
    plt.bar(x + width, metric['data']['aodv'], width, label='AODV', color=colors[2], edgecolor='black')
    
    # Formatting
    plt.title(metric['title'], fontsize=14, fontweight='bold')
    plt.xlabel('Network Scenario', fontsize=12)
    plt.ylabel(metric['ylabel'], fontsize=12)
    plt.xticks(x, [s.capitalize() for s in scenarios], fontsize=11)
    plt.legend()
    plt.grid(axis='y', linestyle='--', alpha=0.7)
    
    # Save to the results folder
    out_file = os.path.join("results", metric['file'])
    plt.savefig(out_file, bbox_inches='tight')
    print(f"Saved plot: {out_file}")

# Display the graphs on your screen
plt.show()
